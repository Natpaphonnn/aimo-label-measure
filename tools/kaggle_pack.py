#!/usr/bin/env python3
"""Generic Kaggle job packager: embed project files + data into one self-contained kernel script and push it.

Usage: python tools/kaggle_pack.py --slug kx-feat-deepseek --entry kaggle/jobs/prefill_job.py \
          --files src/selflabel/prompts.py src/selflabel/answers.py src/features/prefill.py data/pool/problems.jsonl \
          --env MODEL=deepseek-ai/DeepSeek-R1-0528-Qwen3-8B --env PROBLEMS=data/pool/problems.jsonl [--push] [--timeout 7200]
The kernel unpacks the files under /kaggle/working/proj (keeping relative paths), sets the env vars, and execs the entry.
Outputs written by the entry to /kaggle/working/out/ are retrieved with `kaggle kernels output <slug> -p runs/kaggle/<slug>`.
"""
import argparse, base64, io, json, pathlib, subprocess, tarfile
ROOT = pathlib.Path(__file__).resolve().parents[1]
ap = argparse.ArgumentParser()
ap.add_argument("--slug", required=True); ap.add_argument("--entry", required=True); ap.add_argument("--files", nargs="+", required=True)
ap.add_argument("--env", action="append", default=[]); ap.add_argument("--push", action="store_true"); ap.add_argument("--timeout", type=int, default=7200)
ap.add_argument("--no-internet", action="store_true")
ap.add_argument("--kernel-source", action="append", default=[], help="kernel slug whose outputs are mounted under /kaggle/input/<slug>/ (e.g. <kaggle-user>/kx-gen-qwen35-amc-a)")
a = ap.parse_args()
buf = io.BytesIO()
with tarfile.open(fileobj=buf, mode="w:gz") as tar:
    for f in a.files + [a.entry]:
        tar.add(ROOT / f, arcname=f)
blob = base64.b64encode(buf.getvalue()).decode()
env = dict(e.split("=", 1) for e in a.env)
script = f'''# Auto-generated by tools/kaggle_pack.py for {a.slug}; do not edit.
import base64, io, os, pathlib, subprocess, sys, tarfile, time
P = pathlib.Path("/kaggle/working/proj"); P.mkdir(parents=True, exist_ok=True); pathlib.Path("/kaggle/working/out").mkdir(exist_ok=True)
with tarfile.open(fileobj=io.BytesIO(base64.b64decode("{blob}")), mode="r:gz") as tar: tar.extractall(P)
os.environ.update({json.dumps(env)}); os.environ["PROJ"] = str(P); os.environ["OUT"] = "/kaggle/working/out"
sys.path.insert(0, str(P / "src")); os.chdir(P)
print(subprocess.run("nvidia-smi --query-gpu=name,memory.total --format=csv,noheader", shell=True, capture_output=True, text=True).stdout, flush=True)
t0 = time.time(); exec(compile((P / "{a.entry}").read_text(), "{a.entry}", "exec"), {{"__name__": "__main__"}}); print(f"[kaggle_pack] entry finished in {{time.time()-t0:.0f}}s", flush=True)
'''
kdir = ROOT / "runs/kaggle" / a.slug; kdir.mkdir(parents=True, exist_ok=True)
(kdir / "kernel.py").write_text(script)
(kdir / "kernel-metadata.json").write_text(json.dumps({"id": f"<kaggle-user>/{a.slug}", "title": a.slug, "code_file": "kernel.py", "language": "python", "kernel_type": "script",
    "is_private": "true", "enable_gpu": "true", "enable_internet": "false" if a.no_internet else "true", **({"kernel_sources": a.kernel_source} if a.kernel_source else {})}, indent=1))
print(f"packed {len(a.files)+1} files ({len(script)//1024} KB) -> {kdir}; env {env}")
if a.push:
    kaggle = pathlib.Path.home() / "Library/Application Support/pipx/venvs/kaggle/bin/kaggle"
    r = subprocess.run([str(kaggle) if kaggle.exists() else "kaggle", "kernels", "push", "-p", str(kdir), "-t", str(a.timeout)], capture_output=True, text=True); print((r.stdout + r.stderr).strip())
